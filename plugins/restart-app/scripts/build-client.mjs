#!/usr/bin/env node
/**
 * build-client — regenerate the shipped `client.js` from `src/client.js`.
 *
 * `client.js` is the generated artifact the DSH web client loads; the authored
 * copy lives in `src/client.js`. Rebuild after editing the source so the
 * shipped bundle never lags it.
 *
 * Usage
 *   node scripts/build-client.mjs           rewrite client.js from src/client.js
 *   node scripts/build-client.mjs --check   verify only; exit 1 when stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Script } from 'node:vm'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const SOURCE = join(ROOT, 'src', 'client.js')
const BUNDLE = join(ROOT, 'client.js')
const BANNER = '// Generated by scripts/build-client.mjs from src/client.js; edit the source and rebuild.\n'

const source = readFileSync(SOURCE, 'utf8')
if (!source.includes("id: '@local/restart-app'")) {
  throw new Error('src/client.js does not declare the @local/restart-app module id')
}
// Compile without executing, so a syntax error fails the build.
new Script(source, { filename: SOURCE })

const next = BANNER + source
const original = readFileSync(BUNDLE, 'utf8')
const stale = next !== original
if (process.argv.includes('--check')) {
  console.log(stale
    ? 'client.js is stale relative to src/client.js; run this script without --check'
    : 'client.js matches src/client.js')
  process.exit(stale ? 1 : 0)
}
writeFileSync(BUNDLE, next)
console.log(stale
  ? 'client.js rebuilt from src/client.js'
  : 'client.js content already matched src/client.js; bundle re-stamped')
